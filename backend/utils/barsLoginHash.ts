import crypto from 'node:crypto';

/**
 * Хэш логина БАРС — ключ, по которому бот и PWA находят одного и того же
 * пользователя.
 *
 * Зачем он нужен. Идентификатором человека теперь служит userId (UUID), но он
 * выдаётся при первом входе, и бот с PWA входят независимо: тот же человек
 * получил бы два разных userId и увидел бы два разных аккаунта — свои ДЗ в
 * одном приложении и не свои в другом. Общая точка — только логин БАРС.
 *
 * Почему sha256, а не сам логин. Логин — это персональные данные, и хранить
 * его в открытом виде в индексе незачем: хэша достаточно, чтобы сравнивать,
 * и он не читается. Нормализация обязательна: БАРС не различает регистр и
 * пробелы, а человек набирает логин как попало, поэтому «Ivanov », «ivanov» и
 * «Ivanov» обязаны сойтись в один ключ — иначе один человек получил бы два
 * аккаунта.
 *
 * Перебор по хэшу невозможен: логины БАРС — это фамилия и инициалы, вариантов
 * мало, но сам хэш ничего не раскрывает, а угадывание всё равно упирается в
 * проверку пароля перед выдачей токена (см. routes/auth.ts).
 */
export function computeBarsLoginHash(login: string): string {
  const normalized = login.trim().toLowerCase();
  return crypto.createHash('sha256').update(normalized, 'utf-8').digest('hex');
}

/** Нормализованный вид логина — им же сравниваются записи пользователей. */
export function normalizeBarsLogin(login: string): string {
  return login.trim().toLowerCase();
}