/**
 * Общие хелперы парсеров личного кабинета БАРС.
 *
 * Каждый парсер разбирает свой раздел ЛК (оценки, пропуски, приказы и т. д.),
 * но нормализация текста ячеек у них одна и та же. Раньше она была скопирована
 * в каждый файл, и копии расходились: правку «убрать &nbsp;» приходилось
 * повторять четыре раза.
 *
 * Формально это не «свалка utils»: модуль отвечает ровно за одну вещь —
 * приведение текста, выдранного из HTML, к сравнимому виду.
 */

/**
 * Нормализация текста ячейки: HTML-сущность `&nbsp;`, неразрывный пробел,
 * схлопывание любых пробельных последовательностей и обрезка краёв.
 *
 * Используется оценками, пропусками и данными студента. У рейтинга своя,
 * более узкая версия — см. cleanSpaces ниже.
 */
export function cleanText(text: string): string {
  return text
    .replace(/&nbsp;/g, ' ')
    .replace(/\u00a0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * То же, но без явной замены `&nbsp;`: страница рейтинга отдаёт значения числами
 * и сущностью `&nbsp;` не размечает. Отдельная функция сохранена намеренно —
 * подмена её на cleanText расширила бы нормализацию и могла изменить результат
 * на неожиданных данных.
 */
export function cleanSpaces(text: string): string {
  return text.replace(/\u00a0/g, ' ').replace(/\s+/g, ' ').trim();
}
