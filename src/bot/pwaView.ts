/**
 * Экраны бота: приветствие, привязка Telegram и включение уведомлений.
 *
 * Бот перестал быть интерфейсом и стал тонким каналом доставки: расписание,
 * задания, оценки и почта живут в веб-приложении, а отсюда приходят только
 * уведомления. Поэтому здесь нет ни одного экрана с данными — только входная
 * дверь и управление подпиской.
 *
 * Как устроена привязка. Вход в PWA — логином и паролем БАРС, он создаёт
 * запись с userId, и telegramId у неё нет. В приложении человек жмёт «Подключить
 * уведомления», и его перебрасывает в бота с командой `/start <userId>`. Бот
 * находит запись по этому userId и привязывает к ней свой telegramId. Токен
 * бота для этого не нужен и не используется: привязка идёт по адресу записи,
 * а Telegram и так подтвердил, кто прислал `/start`.
 *
 * Что из этого следует. Во-первых, `/start` без адреса не создаёт запись в базе:
 * иначе каждый, кто случайно напишет боту, появился бы в users.json без
 * авторизации. Во-вторых, привязка возможна только к существующей записи PWA —
 * поэтому на «/start <userId>» без такой записи нужен понятный отказ, а не
 * тишина.
 *
 * Про `userId` в ссылке: это не секрет, а идентификатор. Он и так виден
 * человеку в его собственном приложении, а доступ к данным защищён токеном
 * PWA-сессии, а не знанием адреса записи.
 */

import type { ServerFileRef } from '../storage/fileStore.ts';
import { b, i, joinBlocks, link, quote, RULE } from './format.ts';

/** Кнопка Telegram под строкой. */
export interface InlineButton {
  text: string;
  callback_data: string;
  /**
   * Цвет кнопки Telegram. Палитра сокращена до трёх значений: раньше здесь
   * было семнадцать тонов под все экраны бота, а у пуш-канала остались
   * три состояния — «включено», «выключено» и обычное действие.
   */
  style?: 'danger' | 'success' | 'primary';
}

/** Что возвращает экран бота: текст и клавиатура. */
export interface BotViewResult {
  text: string;
  keyboard: InlineButton[][];
  filesToSend?: ServerFileRef[];
}

/** Кнопка. Стиль задаётся явно: у пуш-канала цвет несёт смысл. */
function button(
  text: string,
  callbackData: string,
  style?: InlineButton['style'],
): InlineButton {
  return style ? { text, callback_data: callbackData, style } : { text, callback_data: callbackData };
}

/**
 * Публичный адрес PWA или null, если он не задан.
 *
 * Кнопка появляется только при заданном PWA_URL: незаполненная переменная
 * окружения не должна превращаться в кнопку, которая ведёт в никуда.
 */
export function getPwaUrl(): string | null {
  const raw = process.env.PWA_URL?.trim();
  if (!raw) return null;

  try {
    // Хвостовой слэш убираем: адрес склеивается с путём, и двойной слэш после
    // домена выглядел бы в ссылке неаккуратно.
    const url = new URL(raw);
    const isLocalHttp = url.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    if (url.protocol !== 'https:' && !isLocalHttp) return null;
    return `${url.origin}${url.pathname.replace(/\/+$/, '')}`;
  } catch {
    console.warn('[PWA] PWA_URL задан, но не разбирается как URL — кнопка скрыта');
    return null;
  }
}

/**
 * Ссылка на приложение или текст-заглушка, если PWA не настроена.
 *
 * Заглушка вместо пустой строки: иначе человек увидит экран, на котором
 * обещали приложение, но открыть его нечем, и решит, что всё сломалось.
 * Ссылка остаётся в сообщении; отдельной кнопки перехода на сайт нет.
 */
function appLink(): string {
  const url = getPwaUrl();

  return url
    ? link(url, '🌐 Открыть приложение')
    : quote('Веб-приложение ещё не настроено на сервере.');
}

/**
 * Приветствие: человек написал боту, но ещё ничего не подключил.
 *
 * Здесь важно не перегружать экран. Расписание, оценки и почта — в приложении,
 * и упоминать их нужно одной строкой: перечисление разделов здесь выглядело бы
 * как попытка конкурировать с интерфейсом, которого у бота больше нет.
 */
export function buildWelcomeView(): BotViewResult {
  return {
    text: joinBlocks([
      `👋 ${b('Hub')}`,
      '',
      'Расписание, задания, оценки и почта — в приложении.',
      'Войдите логином и паролем от личного кабинета МЭИ:',
      '',
      appLink(),
      '',
      b('Установка PWA'),
      'iPhone: откройте ссылку в Safari → «Поделиться» → «На экран Домой» → «Добавить».',
      'Android: откройте ссылку в Chrome → меню ⋮ → «Установить приложение» или «Добавить на главный экран».',
      '',
      'Я пришлю уведомление, когда появится новая оценка, придёт письмо ' +
        'или изменится стипендия.',
      '',
      i('Чтобы включить уведомления: откройте приложение, профиль и нажмите ' +
        '«Подключить уведомления в Telegram».'),
    ]),
    keyboard: [],
  };
}

/**
 * Уведомления уже подключены: человек пришёл повторно, ничего подключать не надо.
 *
 * Кнопка включения здесь лишняя: уведомления и так работают, а предлагать
 * включить их повторно — путать человека.
 */
export function buildAlreadyLinkedView(): BotViewResult {
  return {
    text: joinBlocks([
      `🔔 ${b('Уведомления подключены')}`,
      '',
      'Я пришлю сообщение, когда появится новая оценка, придёт письмо ' +
        'или изменится стипендия.',
      '',
      'Расписание, задания и оценки — в приложении:',
      '',
      appLink(),
    ]),
    keyboard: [],
  };
}

/** Привязка состоялась: подтверждаем и даём одну команду на выключение. */
export function buildNotificationsOnView(): BotViewResult {
  return {
    text: joinBlocks([
      `✅ ${b('Уведомления включены')}`,
      '',
      'Я пришлю сообщение, когда появится новая оценка, придёт письмо ' +
        'или изменится стипендия.',
      '',
      RULE,
      '',
      i('Выключить: кнопка ниже. Включить обратно можно в приложении — ' +
        'в разделе «Кабинет».'),
    ]),
    keyboard: [
      [button('🔕 Выключить уведомления', 'notif_off', 'danger')],
    ],
  };
}

/** Уведомления выключены: подтверждаем и оставляем путь обратно. */
export function buildNotificationsOffView(): BotViewResult {
  return {
    text: joinBlocks([
      `🔕 ${b('Уведомления выключены')}`,
      '',
      i('Я ничего не буду присылать, пока вы их не включите.'),
      '',
      i('Включить обратно можно здесь или в приложении — в разделе «Кабинет».'),
    ]),
    keyboard: [
      [button('🔔 Включить уведомления', 'notif_on', 'success')],
    ],
  };
}

/**
 * Адрес из `/start` не найден.
 *
 * Случаи два: человек ещё не входил в приложение, либо перешёл по старой
 * ссылке. Оба лечатся одним действием — открыть приложение, — поэтому и текст
 * здесь один, без попытки различить причины, о которых бот ничего не знает.
 */
export function buildAccountNotFoundView(): BotViewResult {
  return {
    text: joinBlocks([
      `⚠️ ${b('Аккаунт не найден')}`,
      '',
      'Откройте приложение и войдите заново — после этого уведомления ' +
        'подключатся одной кнопкой.',
      '',
      appLink(),
    ]),
    keyboard: [],
  };
}

/**
 * Эран `/app` — то же приветствие, что и при первом `/start`.
 *
 * Отдельный экран убран: показывать то же самое два разными текстами незачем,
 * а различать их больше нечем.
 */
export function buildPwaOpenView(_telegramId: number): BotViewResult {
  return buildWelcomeView();
}
