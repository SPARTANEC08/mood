import { useEffect, useRef, type ReactNode } from 'react';

/**
 * Каркас экрана: шапка сверху, содержимое, ничего лишнего снизу.
 *
 * Два режима содержимого:
 *
 * - обычный (по умолчанию) — лента прокручивается целиком, шапка уезжает вверх.
 *   Так ведут себя почти все экраны приложения;
 * - `fill` — содержимое занимает всю высоту экрана и само управляет прокруткой.
 *   Нужен расписанию: там полоса дат неподвижна, а прокручиваются только дни под
 *   ней, и каждый день — своя страница со своим скроллом (см. DayPager).
 *   Без этого режима полоса уезжала бы вместе с содержимым, а страницы дней не
 *   могли бы иметь свою высоту. Боковых отступов в этом режиме у обёртки нет,
 *   см. комментарий внутри.
 *
 * Почему документ не прокручивается: нижняя панель навигации стоит под этим
 * блоком в той же колонке на всю высоту экрана (см. #root в index.css). Если бы
 * прокручивался документ, положение «низа» зависело бы от длины содержимого, и
 * на коротком экране панель подползала вверх.
 */
export function Page({
  header,
  children,
  /**
   * При изменении этого значения лента прокручивается к началу.
   *
   * Нужен там, где один экран показывает разное содержимое по переключателю:
   * без сброса смена дня на ленте, прокрученной к концу, оставляла бы новый
   * день открытым с конца — то есть пустым экраном. В режиме fill прокручивается
   * уже не этот блок, а страницы по очереди, поэтому ключ там лишний.
   */
  resetKey,
  /** Содержимое занимает всю высоту и прокручивается само (см. описание выше). */
  fill = false,
}: {
  header?: ReactNode;
  children: ReactNode;
  resetKey?: string | number | null;
  fill?: boolean;
}) {
  const scrollRef = useRef<HTMLDivElement | null>(null);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: 0 });
  }, [resetKey]);

  return (
    <div className="flex min-h-0 flex-1 flex-col">
      {header ? <div className="shrink-0">{header}</div> : null}

      {fill ? (
        <div className="flex min-h-0 flex-1 flex-col overflow-hidden">
          {/*
            Боковых отступов у обёртки в режиме fill НЕТ — и это не недосмотр.

            Единственный потребитель fill — экран расписания, где внутри лежит
            карусель дней. Отступ на обёртке сдвигал сам трек карусели внутрь
            экрана на 16px, и при свайпе соседние дни выезжали не из края
            экрана, а из-под этого отступа: у краёв оставалась вертикальная
            полоса фона, в которой было видно обрезанные карточки соседа, а
            карточки активного и соседнего дня смыкались без зазора.

            Отступ нужен внутри страницы, а не на треке: тогда трек занимает
            всю ширину, соседний день выезжает ровно из-за края, а у активного
            дня отступ остаётся прежним. Поэтому здесь только pt-3, а px-4
            ставит сам SchedulePage: полосе дат (обертка сверху) и каждой
            странице дня (pageClassName у DayPager).
          */}
          <div className="mx-auto flex min-h-0 w-full max-w-[560px] flex-1 flex-col pt-3">
            {children}
          </div>
        </div>
      ) : (
        // min-h-0 обязателен: во flex-колонке по умолчанию flex-элемент не может
        // стать ниже своего содержимого, и прокрутка просто не заработает.
        <div
          ref={scrollRef}
          className="scroll-hidden min-h-0 flex-1 overflow-y-auto overscroll-contain"
        >
          <div className="mx-auto max-w-[560px] px-4 pt-3 pb-8">{children}</div>
        </div>
      )}
    </div>
  );
}
