/**
 * Кэш содержимого файлов в памяти.
 *
 * Зачем: файлы закрыты заголовком с токеном, поэтому их содержимое забирает
 * `fetch`, и повторное открытие того же файла без кэша снова уходило бы в сеть.
 * Здесь блоб кладётся в память при скачивании (см. api.downloadFile), и
 * повторное скачивание того же файла обходится без сети.
 *
 * Полноэкранного просмотра в приложении больше нет — файлы открываются в Safari
 * по короткоживущей share-ссылке, а этот кэш обслуживает только скачивание.
 *
 * Почему именно память, а не Cache Storage: вкладка с приложением открывается
 * ненадолго и обычно одна. Кэш Storage пережил бы закрытие, но тогда его надо
 * инвалидировать при выходе из аккаунта и при удалении файла, иначе следующий
 * человек на этом же телефоне получит чужой файл из кэша. Блок, переживающий
 * только текущую сессию, такой ошибки не может дать по построению.
 */

/**
 * Потолок на один файл.
 *
 * Файл крупнее этого не кэшируется вовсе: держать его в памяти телефона ради
 * ускорения одного открытия — обмен, который не окупается. Такой файл откроется
 * как обычно, через сеть.
 */
export const MAX_CACHED_FILE_BYTES = 20 * 1024 * 1024;

/**
 * Потолок на весь кэш.
 *
 * Ограничения на один файл недостаточно: двадцать файлов по 20 МБ — это 400 МБ,
 * а мобильный Safari сбрасывает вкладку, не дожидаясь объяснений. Общий потолок
 * закрывает именно этот случай, а не абстрактный «OOM». При его достижении
 * вытесняется самый старый блоб — по порядку добавления.
 *
 * Значение подобрано так, чтобы типичная лента (несколько десятков мелких файлов)
 * помещалась целиком, а выход за него приходился на редкий тяжёлый случай.
 */
export const MAX_TOTAL_CACHED_BYTES = 80 * 1024 * 1024;

/** Готовые блобы. Порядок вставки = порядок вытеснения. */
const blobs = new Map<string, Blob>();

let totalBytes = 0;

/** Текущий объём кэша — для проверок в консоли и диагностики. */
export function fileCacheBytes(): number {
  return totalBytes;
}

/** Сколько файлов в кэше. */
export function fileCacheSize(): number {
  return blobs.size;
}

export function getCachedFile(fileId: string): Blob | null {
  return blobs.get(fileId) ?? null;
}

/**
 * Кладёт блоб в кэш, вытесняя старое при нехватке общего потолка.
 *
 * Возвращает, занял ли файл место. Крупные файлы и содержимое, не помещающееся
 * даже в пустой кэш, молча пропускаются: вызывающий код не должен решать,
 * кэшировалось что-то или нет.
 */
export function putCachedFile(fileId: string, blob: Blob): boolean {
  if (blob.size > MAX_CACHED_FILE_BYTES) return false;

  const existing = blobs.get(fileId);
  if (existing) totalBytes -= existing.size;

  // Вытесняем до вставки, иначе «файл не влезает» при полном кэше вытеснил бы
  // половину содержимого и всё равно не записался.
  while (totalBytes + blob.size > MAX_TOTAL_CACHED_BYTES && blobs.size > 0) {
    const oldest = blobs.keys().next();
    if (oldest.done) break;
    const victim = blobs.get(oldest.value);
    blobs.delete(oldest.value);
    totalBytes -= victim?.size ?? 0;
  }

  if (totalBytes + blob.size > MAX_TOTAL_CACHED_BYTES) return false;

  blobs.set(fileId, blob);
  totalBytes += blob.size;
  return true;
}

export function clearFileCache(): void {
  blobs.clear();
  totalBytes = 0;
}
