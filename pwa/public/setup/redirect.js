/*
 * iOS сохраняет в иконку текущий URL. Если ставить с /setup/, иконка будет
 * открывать инструкцию вместо приложения, поэтому сразу подменяем адрес на /.
 * Сама страница остаётся открытой — пользователь дочитывает шаги и нажимает
 * «Поделиться» уже с правильным URL.
 */
try {
  if (location.pathname === '/setup' || location.pathname === '/setup/') {
    history.replaceState(null, '', '/');
  }
} catch {
  // Приватный режим или старый WebView: страница всё равно покажет инструкцию.
}
